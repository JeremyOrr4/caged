func TestRefFor(t *testing.T) {
	t.Parallel()

	if got := RefFor(nil); got != BaseRef {
		t.Errorf("RefFor(nil) = %q, want %q", got, BaseRef)
	}
	if got := RefFor(&plan.Extension{Apt: []string{"vim"}}); got != ExtensionRef {
		t.Errorf("RefFor(ext) = %q, want %q", got, ExtensionRef)
	}
}

func TestExtensionDockerfileIsGenerated(t *testing.T) {
	t.Parallel()

	ext := plan.Extension{Source: "~/.config/caged/image.json", Apt: []string{"neovim", "shellcheck", "tmux"}}
	target := Extension(ext, "sha256:base", "0.1.0")
	want := `# Generated by caged from the user's image.json. Do not edit.
FROM caged-runtime:latest
USER root
RUN apt-get update \
    && apt-get install -y --no-install-recommends neovim shellcheck tmux \
    && rm -rf /var/lib/apt/lists/*
USER caged
`
	if len(target.Files) != 1 || target.Files[0].Name != "Dockerfile" || string(target.Files[0].Data) != want || target.Files[0].Mode != 0o644 {
		t.Fatalf("Extension() files = %+v, want one Dockerfile:\n%s", target.Files, want)
	}
}

func TestExtensionTarget(t *testing.T) {
	t.Parallel()

	ext := plan.Extension{Source: "~/.config/caged/image.json", Apt: []string{"neovim", "tmux"}}
	target := Extension(ext, "sha256:base", "0.1.0")
	if target.Role != RoleExtension || target.Ref != ExtensionRef || target.Version != "0.1.0" || target.ContextName != "caged-extension" {
		t.Fatalf("Extension() = %+v", target)
	}
	if want := "~/.config/caged/image.json (apt: neovim, tmux)"; target.Source != want {
		t.Fatalf("Source = %q, want %q", target.Source, want)
	}
	wantLabels := []plan.Label{
		{Key: LabelBaseID, Value: "sha256:base"},
		{Key: LabelExtensionHash, Value: ContextHash(target.Files)},
		{Key: LabelRole, Value: "extension"},
		{Key: LabelVersion, Value: "0.1.0"},
	}
	if got := target.Spec(plan.BuildOptions{}).Labels; !reflect.DeepEqual(got, wantLabels) {
		t.Fatalf("Labels = %+v, want %+v", got, wantLabels)
	}
}

func TestExtensionHashChangesOnlyWithThePackageSet(t *testing.T) {
	t.Parallel()

	hash := func(source, baseID, version string, apt ...string) string {
		target := Extension(plan.Extension{Source: source, Apt: apt}, baseID, version)
		return target.labelValue(LabelExtensionHash)
	}
	want := hash("~/a.json", "sha256:one", "0.1.0", "neovim", "tmux")
	for name, got := range map[string]string{
		"another source file": hash("~/b.json", "sha256:one", "0.1.0", "neovim", "tmux"),
		"another base":        hash("~/a.json", "sha256:two", "0.1.0", "neovim", "tmux"),
		"another version":     hash("~/a.json", "sha256:one", "0.2.0", "neovim", "tmux"),
	} {
		if got != want {
			t.Errorf("hash changed with %s: %q != %q", name, got, want)
		}
	}
	for name, got := range map[string]string{
		"an added package":   hash("~/a.json", "sha256:one", "0.1.0", "neovim", "tmux", "shellcheck"),
		"a removed package":  hash("~/a.json", "sha256:one", "0.1.0", "neovim"),
		"a replaced package": hash("~/a.json", "sha256:one", "0.1.0", "neovim", "tmux2"),
	} {
		if got == want {
			t.Errorf("hash did not change with %s", name)
		}
	}
}

func TestExtensionAssessAgainstTheBase(t *testing.T) {
	t.Parallel()

	target := Extension(plan.Extension{Source: "s", Apt: []string{"vim"}}, "sha256:base", "0.1.0")
	labels := map[string]string{
		LabelRole: "extension", LabelExtensionHash: target.labelValue(LabelExtensionHash), LabelBaseID: "sha256:base", LabelVersion: "0.1.0",
	}
	if got := target.Assess(labels, true); got.State != StateCurrent {
		t.Fatalf("Assess(current) = %+v", got)
	}
	labels[LabelBaseID] = "sha256:rebuilt"
	if got := target.Assess(labels, true); got.State != StateChanged {
		t.Fatalf("Assess(base rebuilt) = %+v, want StateChanged", got)
	}
}

func TestExtensionNoticeDescribeAndWrapBuildError(t *testing.T) {
	t.Parallel()

	target := Extension(plan.Extension{Source: "~/.config/caged/image.json", Apt: []string{"neovim", "tmux"}}, "sha256:base", "0.1.0")
	wantNotice := "Building image extension from ~/.config/caged/image.json (apt: neovim, tmux)..."
	for _, state := range []State{StateMissing, StateUnlabeled, StateChanged} {
		if got := target.Notice(Freshness{State: state, BuiltBy: "0.0.1"}); got != wantNotice {
			t.Errorf("Notice(%v) = %q, want %q", state, got, wantNotice)
		}
	}
	if got := target.Notice(Freshness{State: StateCurrent}); got != "" {
		t.Errorf("Notice(current) = %q, want nothing", got)
	}
	if got, want := target.Describe(), "extension from ~/.config/caged/image.json (apt: neovim, tmux) -> caged-runtime:ext"; got != want {
		t.Errorf("Describe() = %q, want %q", got, want)
	}
	cause := errors.New("exit status 100")
	wrapped := target.WrapBuildError(cause)
	if want := "building the image extension from ~/.config/caged/image.json failed; fix or remove that file: exit status 100"; wrapped.Error() != want || !errors.Is(wrapped, cause) {
		t.Errorf("WrapBuildError() = %v, want %q wrapping the cause", wrapped, want)
	}
	if !strings.Contains(wrapped.Error(), "fix or remove that file") {
		t.Error("the advice is missing")
	}
}
