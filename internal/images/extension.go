package images

import (
	"fmt"
	"strings"

	"github.com/JeremyOrr4/caged/internal/plan"
)

// RefFor returns the image a run uses: the extension image when the user has
// an extension, else the runtime image.
func RefFor(ext *plan.Extension) string {
	if ext != nil {
		return ExtensionRef
	}
	return BaseRef
}

// Extension returns the image that adds the user's apt packages on top of the
// runtime image with ID baseID. Its build context depends only on the package
// list, so the hash is stable.
func Extension(ext plan.Extension, baseID, version string) Target {
	files := []plan.File{{Name: "Dockerfile", Label: "Dockerfile", Data: []byte(extensionDockerfile(ext.Apt)), Mode: 0o644}}
	return Target{
		role:  RoleExtension,
		Ref:   ExtensionRef,
		Files: files,
		Identity: []plan.Label{
			{Key: LabelRole, Value: string(RoleExtension)},
			{Key: LabelExtensionHash, Value: ContextHash(files)},
			{Key: LabelBaseID, Value: baseID},
		},
		version:     version,
		ext:         ext,
		contextName: "caged-extension",
	}
}

// extensionSource names where an extension came from: its config file and
// its package list.
func (t Target) extensionSource() string {
	return fmt.Sprintf("%s (apt: %s)", t.ext.Source, strings.Join(t.ext.Apt, ", "))
}

// extensionDockerfile generates the Dockerfile of an extension. The packages
// have been validated, so they cannot carry shell syntax.
func extensionDockerfile(apt []string) string {
	return "# Generated by caged from image.apt in the user's config.yaml. Do not edit.\n" +
		"FROM " + BaseRef + "\n" +
		"USER root\n" +
		"RUN apt-get update \\\n" +
		"    && apt-get install -y --no-install-recommends " + strings.Join(apt, " ") + " \\\n" +
		"    && rm -rf /var/lib/apt/lists/*\n" +
		"USER caged\n"
}
